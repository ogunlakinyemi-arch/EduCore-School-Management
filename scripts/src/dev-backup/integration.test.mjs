// This test creates TWO private local clusters and fictional records only.
// It NEVER reads DATABASE_URL/PG credentials or connects to live Development.
import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createDisposable, databaseClient, verifyToolchain } from "./processes.mjs";
import { identitySql, identityDigest } from "./safety.mjs";
import { verifyDevelopmentBackup } from "./verification.mjs";
import { captureEvidence, compareEvidence } from "./evidence.mjs";

test("full synthetic dump/restore verifies functions, triggers, all schemas, partitions, sequences, blobs and data", {
  timeout: 180_000,
}, async () => {
  await verifyToolchain();
  const original = await createDisposable();
  const backupRoot = await fs.mkdtemp(path.join(os.homedir(), ".educore-synthetic-backup-"));
  await fs.chmod(backupRoot, 0o700);
  const connection = { ...original.connection, user: "restore_admin" };
  const fixture = databaseClient(connection, false);
  try {
    await fixture.connect();
    await fixture.query(`CREATE SCHEMA fixture_extra;
      CREATE TYPE fixture_extra.status AS ENUM ('NEW','DONE');
      CREATE TABLE public.fixture_parent(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id integer NOT NULL, CONSTRAINT fixture_parent_pair UNIQUE(id,school_id));
      CREATE TABLE fixture_extra.fixture_rows(id integer PRIMARY KEY, parent_id integer,
        school_id integer, label text, amount numeric(12,2), payload jsonb, status fixture_extra.status,
        CONSTRAINT fixture_parent_fk FOREIGN KEY(parent_id,school_id) REFERENCES public.fixture_parent(id,school_id));
      CREATE INDEX fixture_rows_partial ON fixture_extra.fixture_rows(school_id) WHERE amount>0;
      CREATE TABLE public.fixture_audit(id integer);
      CREATE FUNCTION fixture_extra.audit_row() RETURNS trigger LANGUAGE plpgsql AS
        'BEGIN INSERT INTO public.fixture_audit VALUES(NEW.id); RETURN NEW; END';
      CREATE TRIGGER fixture_audit AFTER INSERT ON fixture_extra.fixture_rows
        FOR EACH ROW EXECUTE FUNCTION fixture_extra.audit_row();
      INSERT INTO public.fixture_parent(school_id) VALUES(7),(9);
      INSERT INTO fixture_extra.fixture_rows VALUES
        (1,1,7,'Fictional—not a person',12.50,'{"fixture":true}','NEW'),
        (2,2,9,NULL,NULL,'{"fixture":false}','DONE');
      CREATE VIEW fixture_extra.fixture_view AS SELECT id,amount FROM fixture_extra.fixture_rows;
      CREATE MATERIALIZED VIEW fixture_extra.fixture_summary AS SELECT count(*) AS n FROM fixture_extra.fixture_rows;
      CREATE TABLE public.fixture_partition(id integer, group_id integer) PARTITION BY RANGE(group_id);
      CREATE TABLE public.fixture_partition_first PARTITION OF public.fixture_partition FOR VALUES FROM(0) TO(10);
      INSERT INTO public.fixture_partition VALUES(1,5);
      SELECT lo_from_bytea(0,decode('01020304','hex'));`);
    const identity = (await fixture.query(identitySql)).rows[0];
    const proof = { environment: "development", verifiedBy: "replit-development-read-only",
      verifiedAt: new Date().toISOString(), connection, identity };
    // Synthetic stand-in for independently supplied Development attestation.
    const result = await verifyDevelopmentBackup({ proof,
      confirmation: `DEVELOPMENT:${identityDigest(identity)}`, backupRoot, quiesced: true });
    assert.equal(result.status, "PASS", JSON.stringify(result));
    assert.equal(result.restoreVerified, true);
    assert.equal(result.disposableRemoved, true);
    assert.equal(result.productionConnections, 0);
    assert.equal(result.sourceReadOnly, true);
    const guardedSource = databaseClient(connection, true);
    try {
      await guardedSource.connect();
      await assert.rejects(guardedSource.query("INSERT INTO public.fixture_audit VALUES(99)"),
        error => error.code === "25006");
    } finally { await guardedSource.end(); }
    const files = await fs.readdir(result.backupDirectory);
    assert.ok(files.includes("development.dump"));
    assert.ok(files.includes("before.json") && files.includes("restored.json"));
    for (const name of files) {
      assert.equal((await fs.stat(path.join(result.backupDirectory, name))).mode & 0o077, 0);
    }
    const before = JSON.parse(await fs.readFile(path.join(result.backupDirectory, "before.json"), "utf8"));
    const restored = JSON.parse(await fs.readFile(path.join(result.backupDirectory, "restored.json"), "utf8"));
    compareEvidence(before, restored);
    assert.ok(before.catalog.functions.count > 0 && before.catalog.triggers.count > 0);
    assert.equal(before.largeObjects.rows, "1");
    // Same row counts but changed content MUST fail, without printing row data.
    await fixture.query("UPDATE fixture_extra.fixture_rows SET label='Changed synthetic value' WHERE id=1");
    await fixture.query("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY");
    await fixture.query("SET LOCAL search_path=pg_catalog");
    const changed = await captureEvidence(fixture);
    await fixture.query("ROLLBACK");
    assert.throws(() => compareEvidence(before, changed), /DATA_MISMATCH/);
  } finally {
    await fixture.end();
    await original.stop();
    await fs.rm(backupRoot, { recursive: true });
  }
});
