import { sql } from "drizzle-orm";
import {
  bigserial,
  bigint,
  boolean,
  check,
  foreignKey,
  index,
  integer,
  pgTable,
  serial,
  text,
  timestamp,
  unique,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import {
  appUsers,
  attendanceEvents,
  deviceSchoolBindings,
  employees,
  nfcCards,
  schools,
  students,
} from "./edupulse";

export const securityLocations = pgTable("security_locations", {
  id: serial("id").primaryKey(),
  schoolId: integer("school_id").notNull().references(() => schools.id),
  name: text("name").notNull(),
  description: text("description"),
  zoneType: text("zone_type").notNull().default("OTHER"),
  status: text("status").notNull().default("ACTIVE"),
  createdByUserId: integer("created_by_user_id").references(() => appUsers.id),
  updatedByUserId: integer("updated_by_user_id").references(() => appUsers.id),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  check("security_locations_zone_type_check", sql`${table.zoneType} IN ('GATE','CAMPUS','BUILDING','OTHER')`),
  check("security_locations_status_check", sql`${table.status} IN ('ACTIVE','INACTIVE')`),
  unique("security_locations_name_unique").on(table.schoolId, table.name),
  unique("security_locations_id_school_unique").on(table.id, table.schoolId),
  index("security_locations_school_status_idx").on(table.schoolId, table.status, table.name),
]);

export const securityReaders = pgTable("security_readers", {
  id: serial("id").primaryKey(),
  schoolId: integer("school_id").notNull().references(() => schools.id),
  locationId: integer("location_id").notNull(),
  deviceId: integer("device_id").notNull(),
  name: text("name").notNull(),
  status: text("status").notNull().default("ACTIVE"),
  permissions: text("permissions").array().notNull().default(sql`ARRAY['ENTRY','EXIT']::text[]`),
  createdByUserId: integer("created_by_user_id").references(() => appUsers.id),
  updatedByUserId: integer("updated_by_user_id").references(() => appUsers.id),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  check("security_readers_status_check", sql`${table.status} IN ('ACTIVE','INACTIVE')`),
  check("security_readers_permissions_check", sql`cardinality(${table.permissions}) > 0 AND ${table.permissions} <@ ARRAY['ENTRY','EXIT']::text[]`),
  unique("security_readers_device_school_unique").on(table.schoolId, table.deviceId),
  unique("security_readers_id_school_unique").on(table.id, table.schoolId),
  foreignKey({
    columns: [table.locationId, table.schoolId],
    foreignColumns: [securityLocations.id, securityLocations.schoolId],
    name: "security_readers_location_school_fk",
  }),
  foreignKey({
    columns: [table.deviceId, table.schoolId],
    foreignColumns: [deviceSchoolBindings.deviceId, deviceSchoolBindings.schoolId],
    name: "security_readers_device_school_fk",
  }),
  index("security_readers_school_status_idx").on(table.schoolId, table.status, table.locationId),
]);

export const securityStaffGrants = pgTable("security_staff_grants", {
  id: serial("id").primaryKey(),
  schoolId: integer("school_id").notNull().references(() => schools.id),
  userId: integer("user_id").notNull().references(() => appUsers.id),
  permissions: text("permissions").array().notNull(),
  status: text("status").notNull().default("ACTIVE"),
  expiresAt: timestamp("expires_at", { withTimezone: true }),
  grantedByUserId: integer("granted_by_user_id").notNull().references(() => appUsers.id),
  revokedByUserId: integer("revoked_by_user_id").references(() => appUsers.id),
  revokedAt: timestamp("revoked_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  check("security_staff_grants_permissions_check", sql`cardinality(${table.permissions}) > 0 AND ${table.permissions} <@ ARRAY['READ','MANAGE_READERS','MANAGE_CARDS','REVIEW_PRESENCE','SECURITY_READ','SECURITY_MANAGE','VISITOR_MANAGE','PICKUP_APPROVE','INCIDENT_MANAGE','EMERGENCY_BROADCAST','COMMUNICATION_SEND']::text[]`),
  check("security_staff_grants_status_check", sql`${table.status} IN ('ACTIVE','REVOKED','EXPIRED')`),
  check("security_staff_grants_revocation_shape_check", sql`(${table.status}='ACTIVE' AND ${table.revokedAt} IS NULL AND ${table.revokedByUserId} IS NULL) OR (${table.status} IN ('REVOKED','EXPIRED') AND ${table.revokedAt} IS NOT NULL)`),
  unique("security_staff_grants_id_school_unique").on(table.id, table.schoolId),
  uniqueIndex("security_staff_grants_one_active_unique").on(table.schoolId, table.userId).where(sql`${table.status}='ACTIVE'`),
  index("security_staff_grants_user_idx").on(table.userId, table.schoolId, table.status),
]);

